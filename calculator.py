# Define the entry point for the script
def main():
    """Simple demonstration of calculator operations."""
    a = 5
    b = 3
    print(f"{a} + {b} = {a + b}")
    print(f"{a} - {b} = {a - b}")
    print(f"{a} * {b} = {a * b}")
    print(f"{a} / {b} = {a / b}")

# Execute the entry point only when the script is run directly
if __name__ == "__main__":
    main()
